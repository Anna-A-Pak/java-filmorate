CREATE TABLE IF NOT EXISTS mpa (
    mpa_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mpa_name VARCHAR(5) NOT NULL
);

CREATE TABLE IF NOT EXISTS films (
    film_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_name VARCHAR(200) NOT NULL,
    description VARCHAR(200) NOT NULL,
    release_date DATE NOT NULL,
    duration INTEGER NOT NULL CHECK (duration > 0),
    mpa_id INTEGER NOT NULL REFERENCES mpa ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(200) NOT NULL,
    login VARCHAR(200) NOT NULL,
    user_name VARCHAR(200) NOT NULL,
    birthday DATE NOT NULL CHECK (birthday < CURRENT_DATE)
);

CREATE TABLE IF NOT EXISTS genres (
    genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS films_genres (
    film_id INTEGER NOT NULL REFERENCES films ON DELETE CASCADE,
    genre_id INTEGER NOT NULL REFERENCES genres ON DELETE CASCADE,
    PRIMARY KEY (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS films_likes (
    film_id INTEGER NOT NULL REFERENCES films ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    PRIMARY KEY (film_id, user_id)
);

CREATE TABLE IF NOT EXISTS friendship (
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    friend_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    CHECK (user_id <> friend_id),
    PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE IF NOT EXISTS directors (
    director_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    director_name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS films_directors (
    film_id INTEGER NOT NULL REFERENCES films ON DELETE CASCADE,
    director_id INTEGER NOT NULL REFERENCES directors ON DELETE CASCADE,
    PRIMARY KEY (film_id, director_id)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(200) NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    film_id INTEGER NOT NULL REFERENCES films ON DELETE CASCADE,
    useful INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS users_ratings (
    review_id INTEGER NOT NULL REFERENCES reviews ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    is_positive BOOLEAN NOT NULL,
    PRIMARY KEY (review_id, user_id)
);

CREATE TABLE IF NOT EXISTS events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_stamp BIGINT NOT NULL,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    event_type VARCHAR(10) NOT NULL CHECK (event_type IN ('LIKE', 'REVIEW', 'FRIEND')),
    operation VARCHAR(10) NOT NULL CHECK (operation IN ('ADD', 'UPDATE', 'REMOVE')),
    entity_id INTEGER NOT NULL
);